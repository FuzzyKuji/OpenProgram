#!/usr/bin/env node
// Regenerates components/brand-mark/ink-bounds.generated.ts: where the ink
// of every brand logo (public/images/providers, public/images/channels)
// sits inside its view box. BrandMark sizes a logo by its ink, not by its
// view box, because the logos leave different margins around their marks.
//
// Each SVG is rasterised with sharp at a high resolution; the bounding box
// of its pixels that are at least half covered is converted back to view-box
// units. Rerun it whenever a logo is added or changed:
//
//   npm run generate:brand-ink-bounds --workspace apps/web
//
// A test (tests/brand-mark/brand-mark.test.mjs) reruns the generator and
// fails when the committed file differs.
import { readFileSync, readdirSync, writeFileSync } from "node:fs";
import { join, relative } from "node:path";
import { fileURLToPath } from "node:url";
import sharp from "sharp";

const webRoot = fileURLToPath(new URL("../../", import.meta.url));

/** The folders BrandMark serves logos from, under public/. */
export const BRAND_LOGO_FOLDERS = ["images/providers", "images/channels"];

export const OUTPUT = join(webRoot, "components/brand-mark/ink-bounds.generated.ts");

/** Pixels on the logo's longest view-box side when it is rasterised. */
const RESOLUTION = 2048;
/** A pixel counts as ink from this alpha up (half covered). */
const INK_ALPHA = 128;

const round = (value) => Math.round(value * 100) / 100;

function viewBoxOf(svg, file) {
  const root = svg.match(/<svg\b[^>]*>/)?.[0];
  const box = root?.match(/\bviewBox="([^"]+)"/)?.[1];
  if (!root || !box) throw new Error(`${file}: the root <svg> has no viewBox`);
  const numbers = box.trim().split(/[\s,]+/).map(Number);
  if (numbers.length !== 4 || numbers.some((n) => !Number.isFinite(n))) throw new Error(`${file}: bad viewBox "${box}"`);
  return { root, viewBox: numbers };
}

/** Where a logo's ink sits, in its own view-box units. */
export async function inkBoundsOf(path) {
  return inkBoundsOfSvg(readFileSync(path, "utf8"), path);
}

/** Where the ink of an SVG document sits, in its own view-box units.
 *  `path` names it in errors; `resolution` is the pixels on its longest
 *  view-box side when it is rasterised. */
export async function inkBoundsOfSvg(svg, path, resolution = RESOLUTION) {
  const { root, viewBox } = viewBoxOf(svg, path);
  const [, , boxWidth, boxHeight] = viewBox;
  const perUnit = resolution / Math.max(boxWidth, boxHeight);
  const width = Math.round(boxWidth * perUnit);
  const height = Math.round(boxHeight * perUnit);
  const sizedRoot = root
    .replace(/\s(width|height)="[^"]*"/g, "")
    .replace(/^<svg\b/, `<svg width="${width}" height="${height}"`);
  const { data, info } = await sharp(Buffer.from(svg.replace(root, sizedRoot)))
    .ensureAlpha()
    .raw()
    .toBuffer({ resolveWithObject: true });
  let left = info.width, top = info.height, right = -1, bottom = -1;
  for (let y = 0; y < info.height; y++) {
    for (let x = 0; x < info.width; x++) {
      if (data[(y * info.width + x) * info.channels + 3] < INK_ALPHA) continue;
      if (x < left) left = x;
      if (x > right) right = x;
      if (y < top) top = y;
      if (y > bottom) bottom = y;
    }
  }
  if (right < 0) throw new Error(`${path}: no ink`);
  const unitsX = boxWidth / info.width;
  const unitsY = boxHeight / info.height;
  return {
    x: round(viewBox[0] + left * unitsX),
    y: round(viewBox[1] + top * unitsY),
    width: round((right + 1 - left) * unitsX),
    height: round((bottom + 1 - top) * unitsY),
    viewBox,
  };
}

/** Every logo file BrandMark can draw, as its public path ("/images/…"). */
export function brandLogoPaths() {
  const publicRoot = join(webRoot, "public");
  return BRAND_LOGO_FOLDERS.flatMap((folder) =>
    readdirSync(join(publicRoot, folder))
      .filter((name) => name.endsWith(".svg"))
      .map((name) => `/${relative(publicRoot, join(publicRoot, folder, name)).split("\\").join("/")}`),
  ).sort();
}

/** The text of ink-bounds.generated.ts. */
export async function generate() {
  const lines = [];
  for (const path of brandLogoPaths()) {
    const ink = await inkBoundsOf(join(webRoot, "public", path));
    lines.push(`  ${JSON.stringify(path)}: { x: ${ink.x}, y: ${ink.y}, width: ${ink.width}, height: ${ink.height}, viewBox: [${ink.viewBox.join(", ")}] },`);
  }
  return [
    "// Generated by apps/web/scripts/icons/generate-brand-ink-bounds.mjs. Do not edit.",
    "// Regenerate after adding or changing a logo:",
    "//   npm run generate:brand-ink-bounds --workspace apps/web",
    "",
    'import type { InkBounds } from "./fit";',
    "",
    "/** Where the ink of each brand logo sits, in its view-box units, by public path. */",
    "export const INK_BOUNDS: Readonly<Record<string, InkBounds>> = {",
    ...lines,
    "};",
    "",
  ].join("\n");
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  writeFileSync(OUTPUT, await generate());
  console.log(`wrote ${relative(webRoot, OUTPUT)}`);
}
