#!/usr/bin/env node
// Regenerates components/solar-icons/ink-bounds.ts: where the ink
// of every glyph in components/solar-icons/bodies.ts sits inside its view
// box. A SolarIcon with fit="fill" (the composer and the popups it opens)
// crops its view box to that ink, so the glyph's longer side fills its box.
//
// Each body is rasterised with sharp, through the brand-logo generator's
// rasteriser. The 50 % secondary layer of a duotone glyph is part of the
// drawing, so opacity is dropped before rasterising. Rerun it whenever
// bodies.ts changes:
//
//   npm run generate:solar-ink-bounds --workspace apps/web
//
// A test (tests/ui/composer-fill.test.mjs) reruns the generator and fails
// when the committed file differs.
import { readFileSync, writeFileSync } from "node:fs";
import { join, relative } from "node:path";
import { fileURLToPath } from "node:url";

import { inkBoundsOfSvg } from "./generate-brand-ink-bounds.mjs";

const webRoot = fileURLToPath(new URL("../../", import.meta.url));

export const BODIES = join(webRoot, "components/solar-icons/bodies.ts");
export const OUTPUT = join(webRoot, "components/solar-icons/ink-bounds.ts");

/** Pixels on a glyph's longest view-box side when it is rasterised. */
const RESOLUTION = 1024;

/** Every glyph in bodies.ts: its name, body and view box. */
export function solarGlyphs() {
  const text = readFileSync(BODIES, "utf8");
  const bodies = text.slice(text.indexOf("export const SOLAR_BODIES"), text.indexOf("} as const;"));
  const boxes = text.slice(text.indexOf("export const SOLAR_VIEWBOXES"));
  const viewBoxes = new Map([...boxes.matchAll(/^ {2}"([^"]+)": "([^"]+)",$/gm)].map((match) => [match[1], match[2]]));
  return [...bodies.matchAll(/^ {2}"([^"]+)": ("(?:[^"\\]|\\.)*"),$/gm)].map((match) => ({
    name: match[1],
    body: JSON.parse(match[2]),
    viewBox: viewBoxes.get(match[1]) ?? "0 0 24 24",
  }));
}

/** The text of ink-bounds.ts. */
export async function generate() {
  const lines = [];
  for (const { name, body, viewBox } of solarGlyphs()) {
    const opaque = body.replace(/\s(?:fill-)?opacity="[^"]*"/g, "").replaceAll("currentColor", "black");
    const svg = `<svg xmlns="http://www.w3.org/2000/svg" viewBox="${viewBox}" fill="black">${opaque}</svg>`;
    const ink = await inkBoundsOfSvg(svg, name, RESOLUTION);
    lines.push(`  ${JSON.stringify(name)}: { x: ${ink.x}, y: ${ink.y}, width: ${ink.width}, height: ${ink.height}, viewBox: [${ink.viewBox.join(", ")}] },`);
  }
  return [
    "// Generated by apps/web/scripts/icons/generate-solar-ink-bounds.mjs. Do not edit.",
    "// Regenerate after changing bodies.ts:",
    "//   npm run generate:solar-ink-bounds --workspace apps/web",
    "",
    'import type { InkBounds } from "../brand-mark/fit";',
    'import type { SolarIconName } from "./bodies";',
    "",
    "/** Where the ink of each glyph sits, in its view-box units. */",
    "export const SOLAR_INK: Readonly<Record<SolarIconName, InkBounds>> = {",
    ...lines,
    "};",
    "",
  ].join("\n");
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  writeFileSync(OUTPUT, await generate());
  console.log(`wrote ${relative(webRoot, OUTPUT)}`);
}
