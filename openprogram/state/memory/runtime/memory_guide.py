"""``MEMORY.md``: the entry point of a memory workspace.

It is the one file every session sees. Two parts:

- **The map** — what each part of the workspace holds, which subjects
  ``topics/`` covers, what has been active lately. The memory agents keep
  it; the Runtime only writes a first version for a workspace that has
  none, generated from the tree as it stands (each file named by its
  title, never by a quoted fact), and on every write takes out the lines
  of Topics that write removed.
- **The core** — the facts and rules every session needs without asking:
  who the owner is, standing preferences. It is rendered from
  ``topics/core.md`` (the editable, evidence-carrying master) between
  ``CORE_START`` and ``CORE_END``, only from blocks whose evidence is
  trusted and within ``core_max_tokens``. The render replaces that section
  each time; anything outside it is the agents' own.

Files written outside OpenProgram have a third part, generated by code and
kept in the runtime directory (``outside-map.md``), never in ``MEMORY.md``:
a list of them under "Other files", at most a quarter of
``GUIDE_MAX_BYTES``. It is redrawn only where memory installs (a writer,
the organizer, a save in Settings) and when the Worker starts, so the
prompt's memory section changes at most once per write however often
another tool writes.

The prompt shows the map cut to what the list leaves of
``GUIDE_MAX_BYTES``, then the list, then the core.
"""
from __future__ import annotations

import re
from pathlib import Path

GUIDE_FILE = "MEMORY.md"
#: What reaches the prompt; the file itself may be longer.
GUIDE_MAX_BYTES = 6_000
#: Directory depth the generated map lists below ``topics/``.
_MAP_DEPTH = 3
_RECENT = 6

_LAYOUT = """\
## Layout

- The core section at the end of this file — what every session needs, rendered from `topics/core.md`. Edit `topics/core.md`; the section is replaced on every write.
- `topics/` — the organised memory: one file per person, project or recurring theme. A subject with parts of its own is a directory with `overview.md` and one file per part. Paragraphs end in a `^block-id` and cite footnotes that link the chat message they came from, `/s/<session>#<message>`. Pass that link to `memory_get` to read what was actually said.
- `timeline/` — the same facts by date: a file per year, with month and day files below it, for "what happened when".
- `relations.json`, `recent_events.jsonl` — links between paragraphs and the latest changes.

Search with `memory_search` first; read the Topic file a hit points to for the surrounding facts.

To remember something or change what memory holds, use `memory_update` (load it first with `tool_search select:memory_update` when it is not in your tool list). A file written into `topics/` with the file tools is kept exactly as written and found by search, but memory never organises it."""

#: The share of ``GUIDE_MAX_BYTES`` the list of files written outside may
#: take, as Grok Build gives the tail of its generated manifest.
OUTSIDE_SHARE = 4
OUTSIDE_MAP_FILE = "outside-map.md"
#: Of the list's own budget, the part titled entries may take; the rest
#: lists bare paths.
_TITLED_SHARE = (3, 4)


CORE_START = "<!-- core: rendered from topics/core.md, edit that file instead -->"
CORE_END = "<!-- /core -->"
_CORE_SECTION = re.compile(
    re.escape(CORE_START) + r"[\s\S]*?" + re.escape(CORE_END) + r"\n?")


def split(text: str) -> tuple[str, str]:
    """``(map, core)``: the agents' part of the file and the rendered core."""
    found = _CORE_SECTION.search(text or "")
    if not found:
        return (text or "").strip(), ""
    core = found.group(0)[len(CORE_START):].rsplit(CORE_END, 1)[0].strip()
    rest = (text[:found.start()] + text[found.end():]).strip()
    return rest, core


def write_core(memory_dir: Path, core: str) -> None:
    """Put the rendered core into ``MEMORY.md``, keeping the map as it is.

    A workspace without a map gets the generated one first. An empty
    ``core`` removes the section."""
    path = Path(memory_dir) / GUIDE_FILE
    try:
        current = path.read_text(encoding="utf-8")
    except FileNotFoundError:
        current = generate(memory_dir)
    map_text, _old = split(current)
    parts = [map_text]
    if core.strip():
        parts.append(f"{CORE_START}\n{core.strip()}\n{CORE_END}")
    path.write_text("\n\n".join(p for p in parts if p).rstrip() + "\n", encoding="utf-8")


def _map_lines(directory: Path, root: Path, depth: int) -> list[str]:
    lines: list[str] = []
    indent = "  " * depth
    entries = sorted(directory.iterdir(), key=lambda p: (p.is_file(), p.name))
    for entry in entries:
        relative = entry.relative_to(root).as_posix()
        if entry.is_dir():
            overview = entry / "overview.md"
            note = _title(overview) if overview.is_file() else ""
            lines.append(f"{indent}- `{relative}/`" + (f" — {note}" if note else ""))
            if depth + 1 < _MAP_DEPTH:
                lines.extend(_map_lines(entry, root, depth + 1))
        elif (entry.suffix == ".md" and entry.name != "overview.md"
              and entry != root / "topics" / "core.md"):
            note = _title(entry)
            lines.append(f"{indent}- `{relative}`" + (f" — {note}" if note else ""))
    return lines


def _recent_lines(memory_dir: Path) -> list[str]:
    import json

    from ..markdown import read_topic_tree

    events = memory_dir / "recent_events.jsonl"
    if not events.is_file():
        return []
    try:
        paths = {
            u.memory_id: u.topic_path
            for u in read_topic_tree(memory_dir / "topics").units
        }
    except Exception:
        return []
    seen: list[str] = []
    for raw in reversed(events.read_text(encoding="utf-8").splitlines()):
        try:
            event = json.loads(raw)
        except ValueError:
            continue
        topic = paths.get(event.get("memory_id", ""))
        if topic and topic != "core.md" and topic not in seen:
            seen.append(topic)
        if len(seen) >= _RECENT:
            break
    return [f"- `topics/{path}`" for path in seen]


def generate(memory_dir: Path) -> str:
    """A first ``MEMORY.md`` for the workspace as it stands."""
    memory_dir = Path(memory_dir)
    topics = memory_dir / "topics"
    parts = [
        "# Memory map",
        "What this memory holds and where to find it. Memory agents keep this "
        "file current; rewrite it whenever the structure or the current focus changes.",
        _LAYOUT,
    ]
    if topics.is_dir():
        subjects = _map_lines(topics, memory_dir, 0)
        if subjects:
            parts.append("## Subjects\n\n" + "\n".join(subjects))
    recent = _recent_lines(memory_dir)
    if recent:
        parts.append("## Recently active\n\n" + "\n".join(recent))
    return "\n\n".join(parts) + "\n"


def ensure(memory_dir: Path) -> bool:
    """Write the generated map when the workspace has none. True if written."""
    path = Path(memory_dir) / GUIDE_FILE
    if path.exists():
        return False
    path.write_text(generate(memory_dir), encoding="utf-8")
    return True


#: A map entry naming a Topic file or directory: a list item whose first
#: code span is a path under ``topics/``.
_ENTRY = re.compile(r"^\s*[-*+]\s+`(topics/[^`]+)`")


def drop_removed(memory_dir: Path) -> bool:
    """Remove the map's entries for Topic files and directories the tree no
    longer has. True if the file changed.

    A write that deletes a Topic (``memory_update``'s ``delete_record``)
    runs no agent, so nothing else would take its line out, and the map
    reaches every session. The core section is left as it is."""
    memory_dir = Path(memory_dir)
    path = memory_dir / GUIDE_FILE
    try:
        text = path.read_text(encoding="utf-8")
    except OSError:
        return False
    found = _CORE_SECTION.search(text)
    head, core, tail = ((text[:found.start()], found.group(0), text[found.end():])
                        if found else (text, "", ""))

    def kept(part: str) -> str:
        lines = []
        for line in part.splitlines(keepends=True):
            entry = _ENTRY.match(line)
            if entry and not (memory_dir / entry.group(1).rstrip("/")).exists():
                continue
            lines.append(line)
        return "".join(lines)

    updated = kept(head) + core + kept(tail)
    if updated == text:
        return False
    # A heading whose entries are all gone stays: the agents own its shape.
    path.write_text(updated, encoding="utf-8")
    return True


def _title(path: Path) -> str:
    """A file's title: its front matter ``name``, its first heading, or
    nothing (the path stands alone)."""
    try:
        text = path.read_text(encoding="utf-8", errors="replace")
    except OSError:
        return ""
    lines = text.splitlines()
    if lines and lines[0].strip() == "---":
        for line in lines[1:]:
            if line.strip() in ("---", "..."):
                break
            match = re.match(r"^name:\s*(.+?)\s*$", line)
            if match:
                return match.group(1).strip().strip("'\"")
    for line in lines:
        match = re.match(r"^#{1,6}\s+(.+?)\s*$", line)
        if match:
            return match.group(1)
    return ""


def outside_tail(memory_dir: Path, budget: int = GUIDE_MAX_BYTES // OUTSIDE_SHARE) -> str:
    """The "Other files" part of the map: every Topic file written outside
    OpenProgram, in path order, within ``budget`` bytes.

    Titled entries take up to three quarters of the budget, bare paths the
    rest, and a last line counts what did not fit, as Grok Build's
    manifest does. Empty when there are no such files.
    """
    from ..management import ownership

    memory_dir = Path(memory_dir)
    paths = sorted(ownership.outside_paths(memory_dir))
    if not paths:
        return ""
    head = (
        "## Other files\n\n"
        "Written outside OpenProgram: searchable, read-only, kept as they are."
    )
    used = len(head.encode("utf-8"))
    titled_budget = budget * _TITLED_SHARE[0] // _TITLED_SHARE[1]
    lines: list[str] = []

    def more(count: int) -> str:
        return f"{count} more files are not listed"

    for index, relative in enumerate(paths):
        title = _title(memory_dir / "topics" / relative)
        entry = f"- `topics/{relative}`"
        titled = f"{entry} — {title}" if title else entry
        left = len(paths) - index - 1
        # Room is always kept for the count line that may follow.
        reserve = len(("\n" + more(left)).encode("utf-8")) if left else 0
        if title and used + len(("\n" + titled).encode("utf-8")) <= titled_budget:
            line = titled
        elif used + len(("\n" + entry).encode("utf-8")) + reserve <= budget:
            line = entry
        else:
            lines.append(more(len(paths) - index))
            break
        lines.append(line)
        used += len(("\n" + line).encode("utf-8"))
    return head + "\n" + "\n".join(lines)


def _outside_map_path(memory_dir: Path) -> Path:
    from ..workspace_layout import runtime_dir

    return runtime_dir(Path(memory_dir)) / OUTSIDE_MAP_FILE


def refresh_outside_map(memory_dir: Path) -> bool:
    """Redraw the stored list of files written outside. True when it
    changed; unchanged, nothing is written. Never raises."""
    try:
        tail = outside_tail(Path(memory_dir))
        path = _outside_map_path(Path(memory_dir))
        try:
            current = path.read_text(encoding="utf-8")
        except OSError:
            current = None
        if current == tail or (current is None and not tail):
            return False
        if not tail:
            path.unlink(missing_ok=True)
            return True
        from openprogram.state.store.session.atomic_file import atomic_write_text

        path.parent.mkdir(parents=True, exist_ok=True)
        atomic_write_text(path, tail)
        return True
    except Exception:  # noqa: BLE001 - the map never fails a write
        return False


def prompt_text(memory_dir: Path) -> str:
    """``MEMORY.md`` as the prompt shows it: the map cut to what the list
    of files written outside leaves of ``GUIDE_MAX_BYTES``, that list,
    then the core in full (the render already holds it to its own
    budget)."""
    try:
        text = (Path(memory_dir) / GUIDE_FILE).read_text(encoding="utf-8")
    except OSError:
        text = ""
    try:
        tail = _outside_map_path(Path(memory_dir)).read_text(encoding="utf-8").strip()
    except OSError:
        tail = ""
    map_text, core = split(text)
    limit = GUIDE_MAX_BYTES - len(tail.encode("utf-8"))
    data = map_text.encode("utf-8")
    shown = data[:limit].decode("utf-8", errors="ignore").strip()
    if len(data) > limit:
        shown += "\n… (MEMORY.md continues; read it for the rest)"
    if not core:
        core = _legacy_core(Path(memory_dir))
    return "\n\n".join(part for part in (shown, tail, core) if part)


def _legacy_core(memory_dir: Path) -> str:
    """A root ``core.md`` from before the core moved into this file; the
    next write renders it here and removes it."""
    try:
        text = (memory_dir / "core.md").read_text(encoding="utf-8").strip()
    except OSError:
        return ""
    body = [line for line in text.splitlines() if not line.startswith("# ")]
    return text if "\n".join(body).strip() else ""
